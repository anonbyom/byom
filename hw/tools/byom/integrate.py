#!/usr/bin/env python3
import graphlib, json, re, shlex, sys, tomllib
from pathlib import Path

import pyslang
from pyslang import ast, driver

TREE = Path(__file__).resolve().parents[2]
CONFIG = TREE / "fpga" / "config"
SECTIONS = {"TARGET_": (), "DMA_TIMING_": ("dma",), "SHELL_": ("shell",), "SOCKET_": ("array",),
    "SOCKET_OS_": ("array", "os"), "ARITH_": ("arith", "mxu_arith"), "ARITH_MX_": ("arith", "mx"),
    "ARITH_MODES_": ("arith", "modes"), "ARITH_ENCODER_": ("arith", "mxu_arith", "encoder")}

def config_path(kind, name):
    return next(p for p in (CONFIG / kind / f"{name}.toml", *(TREE / "examples").glob(f"*/{kind}/{name}.toml")) if p.exists())

def load(path): return tomllib.loads(path.read_text())

def definitions(path):
    """Which modules and packages a source file defines, and which packages it uses."""
    text = re.sub(r"//[^\n]*|/\*.*?\*/", "", path.read_text(), flags=re.S)
    defines = set(re.findall(r"^\s*(?:module|package)\s+(\w+)", text, re.M))
    return defines, set(re.findall(r"\b(\w+)::", text)) - defines

def unit_sources(unit):
    own = list(unit.get("sources", []))
    own += [f for f in unit.get("adapter", []) if f not in own]
    replaced = set().union(*(definitions(TREE / f)[0] for f in own))
    library = {str(p.relative_to(TREE)): definitions(p) for p in sorted((TREE / "rtl/mxu").rglob("*.sv"))}
    gone = {str(Path(f).parent) + "/" for f, (d, _) in library.items() if d & replaced}
    library = {f: d for f, d in library.items() if f not in own and not f.startswith(tuple(gone))}
    order = graphlib.TopologicalSorter({f: () for f in library})
    for f, (_, uses) in library.items():
        order.add(f, *(g for g, (d, _) in library.items() if g != f and uses & d))
    return own + list(order.static_order())

def variant(image):
    image_toml = load(config_path("images", image))
    base = load(CONFIG / "base" / f"{image_toml['base']}.toml")
    unit = load(config_path("units", image_toml["unit"])) if image_toml["unit"] != "none" else None
    sources = base["sources"] if unit else [s for s in base["sources"] if s != "rtl/vector_mxu.sv"]
    at = sources.index("@unit")
    config = {key: image_toml.get(key, base[key]) for key in ("top", "part", "constraints")}
    config["defines"] = [d for d in base["defines"] if d not in image_toml.get("undefines", [])] + \
        [d for d in image_toml.get("defines", []) if d not in base["defines"]]
    config["sources"] = sources[:at] + (unit_sources(unit) if unit else []) + sources[at + 1:]
    config["parameters"] = {**base["parameters"], **image_toml.get("parameters", {}),
        **({f"MXU_{key.upper()}": x for table in ("shape", "operands", "socket") for key, x in unit.get(table, {}).items()} 
           if unit else {"MXU_ENABLE": False})}
    for key in ("hooks", "directives", "floorplan"):
        table = {**base.get(key, {}), **(unit or {}).get(key, {}), **image_toml.get(key, {})}
        if table:
            config[key] = table
    return config

def render(image, config):
    path = config_path("images", image)
    lines = [path.read_text().split("\n", 1)[0], f"# Generated by tools/byom/integrate.py from {path.relative_to(TREE)}"]
    lines += [f"{key} = {json.dumps(config[key])}" for key in ("top", "part", "constraints", "defines") if key in config]
    lines += ["sources = ["] + [f'    "{s}",' for s in config["sources"]] + ["]", "", "[parameters]"]
    lines += [f"{key} = {json.dumps(x)}" for key, x in config["parameters"].items()]
    for table in ("hooks", "directives", "floorplan"):
        if table in config:
            lines += ["", f"[{table}]"] + [f"{key} = {json.dumps(x)}" for key, x in config[table].items()]
    return "\n".join(lines) + "\n"

def elaborate(config):
    """Elaborates the image and returns the constants of every module, generate block and package."""
    files = [TREE / "tools/byom/dsp48e2_model.sv"] + [TREE / s for s in config["sources"] if s.endswith((".sv", ".v"))]
    params = {key: int(x) if isinstance(x, bool) else x for key, x in config["parameters"].items()}
    args = ["slang", "--top", config["top"], "--single-unit", "--timescale", "1ns/1ps", "-I", TREE / "fpga", "-I",
        TREE / "rtl", *(f"-D{d}" for d in config["defines"]), *(f"-G{key}={x}" for key, x in params.items()), *files]
    slang = driver.Driver()
    slang.addStandardArgs()
    slang.parseCommandLine(" ".join(shlex.quote(str(a)) for a in args))
    slang.processOptions()
    slang.parseAllSources()
    compilation = slang.createCompilation()
    errors = [x for x in compilation.getAllDiagnostics() if x.isError()]
    if errors:
        sys.exit(pyslang.DiagnosticEngine.reportAll(slang.sourceManager, errors)[-3000:])
    kind, (top,) = ast.SymbolKind, compilation.getRoot().topInstances
    if unknown := sorted(set(params) - {s.name for s in top.body if s.kind == kind.Parameter}):
        sys.exit(f"{config['top']}: no parameter {', '.join(unknown)}")

    def number(value):
        match = re.fullmatch(r"(-?)(?:\d+'s?([bodh]))?([0-9a-fA-F]+)", str(value).replace("_", ""))
        if not match:
            return None
        n = int(match.group(3), {"b": 2, "o": 8, "d": 10, "h": 16}[match.group(2) or "d"])
        return -n if match.group(1) else n

    def value(s):
        text = str(s.value)
        return text[1:-1] if s.type.isString else bool(number(text)) if s.type.isScalar else number(text)

    def parameters(scope):
        return {s.name: value(s) for s in scope if s.kind == kind.Parameter}

    found = []

    def visit(symbol, in_unit):
        if symbol.kind == kind.Instance:
            in_unit = in_unit or symbol.body.definition.name == "mxu"
            found.append((in_unit, parameters(symbol.body)))
            for s in symbol.body:
                visit(s, in_unit)
        elif symbol.kind == kind.InstanceArray:
            for element in symbol.elements:
                visit(element, in_unit)
        elif symbol.kind == kind.GenerateBlock and not symbol.isUninstantiated:
            found.append((in_unit, parameters(symbol)))
            for s in symbol:
                visit(s, in_unit)
        elif symbol.kind == kind.GenerateBlockArray:
            for block in symbol.entries:
                visit(block, in_unit)

    visit(top, False)
    return found + [(False, parameters(package)) for package in compilation.getPackages()]

def sections(found):
    d = {}
    for in_unit, params in sorted(found, key=lambda f: f[0]):
        for constant, x in params.items():
            if prefix := max((p for p in SECTIONS if constant.startswith(p)), key=len, default=""):
                *path, key = (*SECTIONS[prefix], constant[len(prefix):].lower())
                target = d
                for part in path:
                    target = target.setdefault(part, {})
                target[key] = x
    return d

def describe(image, config):
    return {"name": image, **sections(elaborate(config))}


if __name__ == "__main__":
    image = sys.argv[1]
    config = variant(image)
    outputs = {CONFIG / "variants" / f"{image}.toml": render(image, config),
        CONFIG / "sidecars" / f"{image}.json": json.dumps(describe(image, config), indent=1, sort_keys=True) + "\n"}
    for target, text in outputs.items():
        target.parent.mkdir(exist_ok=True)
        target.write_text(text)
        print("wrote", target.relative_to(TREE))
