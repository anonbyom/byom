    typedef struct packed {
        logic       sign;
        logic [7:0] exponent;
        logic [6:0] mantissa;
    } input_t;
    typedef struct packed {
        logic        sign;
        logic        nan;
        logic        saturate;        // |x| >= 128 or infinite
        logic        one;             // |x| < 2^-9
        logic        below_one;       // |x| < 1
        logic [11:0] small_index;     // {exponent - SMALL_EXPONENT, sign, mantissa}
        logic [6:0]  fraction_index;  // k
        logic [8:0]  exponent;        // of the result from |x| >= 1; 0 or negative: flushed
    } decoded_t;
    typedef struct packed {
        logic       sign;
        logic       nan;
        logic       saturate;
        logic       one;
        logic       below_one;
        logic [7:0] small_entry;      // {result exponent - 126, mantissa}
        logic [6:0] fraction;
        logic [8:0] exponent;
    } table_t;
    typedef struct packed {
        logic [15:0] value;
    } output_t;

    input_t   input_q;
    decoded_t decoded_d, decoded_q;
    table_t   table_d, table_q;
    output_t  output_d, output_q, result_q;
    logic [LATENCY-1:0] valid_q;
    logic [13:0] magnitude;    // |x| with 7 fraction bits, for 1 <= |x| < 128
    logic [6:0]  whole;
    logic [6:0]  part;

    always_comb begin
        decoded_d = '0;
        magnitude = 14'({1'b1, input_q.mantissa} << 3'(input_q.exponent - 8'd127));
        whole = magnitude[13:7];
        part = magnitude[6:0];
        decoded_d.sign = input_q.sign;
        decoded_d.nan = input_q.exponent == 8'hff && input_q.mantissa != 0;
        decoded_d.saturate = input_q.exponent >= 8'd134;
        decoded_d.one = input_q.exponent < SMALL_EXPONENT;
        decoded_d.below_one = input_q.exponent < 8'd127;
        decoded_d.small_index = {4'(input_q.exponent - SMALL_EXPONENT), input_q.sign, input_q.mantissa};
        // x < 0: n = -whole - 1 and k = 128 - part, unless part = 0.
        decoded_d.fraction_index = input_q.sign ? -part : part;
        decoded_d.exponent = input_q.sign ? 9'd127 - 9'(whole) - 9'(part != 0) : 9'd127 + 9'(whole);
    end

    logic [7:0] small_read;
    // Table read from the decode stage's index: a registered (block RAM) read.
    always_ff @(posedge clk) small_read <= pow2_small(decoded_d.small_index);
    always_comb begin
        table_d = '0;
        table_d.sign = decoded_q.sign;
        table_d.nan = decoded_q.nan;
        table_d.saturate = decoded_q.saturate;
        table_d.one = decoded_q.one;
        table_d.below_one = decoded_q.below_one;
        table_d.small_entry = small_read;
        table_d.fraction = pow2_fraction(decoded_q.fraction_index);
        table_d.exponent = decoded_q.exponent;
    end

    always_comb begin
        output_d = '0;
        if (table_q.nan)
            output_d.value = 16'h7fc0;
        else if (table_q.saturate)
            output_d.value = table_q.sign ? 16'h0000 : 16'h7f80;
        else if (table_q.one)
            output_d.value = 16'h3f80;
        else if (table_q.below_one)
            output_d.value = {1'b0, 8'd126 + 8'(table_q.small_entry[7]), table_q.small_entry[6:0]};
        else if (table_q.exponent == 0 || table_q.exponent[8])
            output_d.value = 16'h0000;
        else
            output_d.value = {1'b0, table_q.exponent[7:0], table_q.fraction};
    end

    always_ff @(posedge clk) begin
        input_q <= '{sign: a[15], exponent: a[14:7], mantissa: a[6:0]};
        decoded_q <= decoded_d;
        table_q <= table_d;
        output_q <= output_d;
        result_q <= output_q;
        valid_q <= {valid_q[LATENCY-2:0], in_valid};
    end
    assign out_valid = valid_q[LATENCY-1];
    assign result = result_q.value;
