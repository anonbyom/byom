    localparam logic [7:0] FIRST_EXPONENT = 8'd123;     // table binades of y: 123..128
    localparam logic [7:0] LAST_EXPONENT  = 8'd128;
    localparam logic [7:0] RESULT_BASE    = 8'd122;     // exponent of table entry 0

    typedef struct packed {
        logic       sign;
        logic [7:0] exponent;
        logic [6:0] mantissa;
        logic       sigmoid;
    } input_t;
    typedef struct packed {
        logic       sign;
        logic [6:0] mantissa;
        logic [8:0] identity_exponent;   // of y (tanh) or y/2 (shifted sigmoid)
        logic [9:0] index;
        logic       sigmoid;
        logic       nan;
        logic       zero;
        logic       saturate;
        logic       identity;
    } decoded_t;
    typedef struct packed {
        logic       sign;
        logic [6:0] mantissa;
        logic [8:0] identity_exponent;
        logic [9:0] fraction;            // {result exponent - RESULT_BASE, mantissa}
        logic       sigmoid;
        logic       nan;
        logic       zero;
        logic       saturate;
        logic       identity;
    } table_t;
    typedef struct packed {
        logic [15:0] value;
    } output_t;

    input_t   input_q;
    decoded_t decoded_d, decoded_q;
    table_t   table_d, table_q;
    output_t  output_d, output_q, result_q;
    logic [LATENCY-1:0] valid_q;
    logic [7:0] y_exponent;

    always_comb begin
        decoded_d = '0;
        y_exponent = input_q.exponent - 8'(input_q.sigmoid);
        decoded_d.sign = input_q.sign;
        decoded_d.mantissa = input_q.mantissa;
        decoded_d.identity_exponent = {1'b0, input_q.exponent} - {7'b0, input_q.sigmoid, 1'b0};
        decoded_d.index = {3'(y_exponent - FIRST_EXPONENT), input_q.mantissa};
        decoded_d.sigmoid = input_q.sigmoid;
        decoded_d.nan = input_q.exponent == 8'hff && input_q.mantissa != 0;
        decoded_d.zero = input_q.exponent == 0;
        decoded_d.saturate = y_exponent > LAST_EXPONENT;
        decoded_d.identity = y_exponent < FIRST_EXPONENT;
    end

    logic [9:0] fraction_read;
    // Table read from the decode stage's index: a registered (block RAM) read.
    always_ff @(posedge clk) fraction_read <= tanh_fraction(decoded_d.index);
    always_comb begin
        table_d = '0;
        table_d.sign = decoded_q.sign;
        table_d.mantissa = decoded_q.mantissa;
        table_d.identity_exponent = decoded_q.identity_exponent;
        table_d.fraction = fraction_read;
        table_d.sigmoid = decoded_q.sigmoid;
        table_d.nan = decoded_q.nan;
        table_d.zero = decoded_q.zero;
        table_d.saturate = decoded_q.saturate;
        table_d.identity = decoded_q.identity;
    end

    always_comb begin
        output_d = '0;
        if (table_q.nan)
            output_d.value = 16'h7fc0;
        else if (table_q.zero || table_q.identity && (table_q.identity_exponent == 0 || table_q.identity_exponent[8]))
            output_d.value = {table_q.sign, 15'h0000};
        else if (table_q.saturate)
            output_d.value = {table_q.sign, 8'd127 - 8'(table_q.sigmoid), 7'h00};
        else if (table_q.identity)
            output_d.value = {table_q.sign, table_q.identity_exponent[7:0], table_q.mantissa};
        else
            output_d.value = {table_q.sign, RESULT_BASE + 8'(table_q.fraction[9:7]) - 8'(table_q.sigmoid), table_q.fraction[6:0]};
    end

    always_ff @(posedge clk) begin
        input_q   <= '{sign: a[15], exponent: a[14:7], mantissa: a[6:0], sigmoid: sigmoid};
        decoded_q <= decoded_d;
        table_q   <= table_d;
        output_q  <= output_d;
        result_q  <= output_q;
        valid_q   <= {valid_q[LATENCY-2:0], in_valid};
    end
    assign out_valid = valid_q[LATENCY-1];
    assign result = result_q.value;
