    typedef struct packed {
        logic       sign;
        logic [7:0] exponent;
        logic [6:0] mantissa;
        logic       rsqrt;
    } input_t;
    typedef struct packed {
        logic       sign;
        logic [8:0] exponent;      // result exponent before the table's decrement
        logic [8:0] index;
        logic       nan;
        logic       zero;
        logic       infinity;
    } decoded_t;
    typedef struct packed {
        logic       sign;
        logic [8:0] exponent;
        logic [7:0] fraction;      // {decrement exponent, mantissa}
        logic       nan;
        logic       zero;
        logic       infinity;
    } table_t;
    typedef struct packed {
        logic [15:0] value;
    } output_t;

    input_t   input_q;
    decoded_t decoded_d, decoded_q;
    table_t   table_d, table_q;
    output_t  output_d, output_q, result_q;
    logic [LATENCY-1:0] valid_q;
    logic [8:0] exponent;

    always_comb begin
        decoded_d = '0;
        decoded_d.sign = input_q.sign;
        decoded_d.nan = input_q.exponent == 8'hff && input_q.mantissa != 0 ||
                        input_q.rsqrt && input_q.sign && input_q.exponent != 0;
        decoded_d.zero = input_q.exponent == 0;
        decoded_d.infinity = input_q.exponent == 8'hff;
        // 1/x: 2^(127 - e) = 254 - E. 1/sqrt(x): 2^(127 - (e >>> 1)) = (382 - E) >> 1.
        decoded_d.exponent = input_q.rsqrt ? (9'd382 - {1'b0, input_q.exponent}) >> 1 : 9'd254 - {1'b0, input_q.exponent};
        decoded_d.index = {input_q.rsqrt, input_q.rsqrt && !input_q.exponent[0], input_q.mantissa};
    end

    logic [7:0] fraction_read;
    // Table read from the decode stage's index: a registered (block RAM) read.
    always_ff @(posedge clk) fraction_read <= reciprocal_fraction(decoded_d.index);
    always_comb begin
        table_d = '0;
        table_d.sign = decoded_q.sign;
        table_d.exponent = decoded_q.exponent;
        table_d.fraction = fraction_read;
        table_d.nan = decoded_q.nan;
        table_d.zero = decoded_q.zero;
        table_d.infinity = decoded_q.infinity;
    end

    always_comb begin
        output_d = '0;
        exponent = table_q.exponent - 9'(table_q.fraction[7]);
        if (table_q.nan)
            output_d.value = 16'h7fc0;
        else if (table_q.zero)
            output_d.value = {table_q.sign, 15'h7f80};
        else if (table_q.infinity || exponent == 0 || exponent[8])
            output_d.value = {table_q.sign, 15'h0000};
        else
            output_d.value = {table_q.sign, exponent[7:0], table_q.fraction[6:0]};
    end

    always_ff @(posedge clk) begin
        input_q   <= '{sign: a[15], exponent: a[14:7], mantissa: a[6:0], rsqrt: rsqrt};
        decoded_q <= decoded_d;
        table_q   <= table_d;
        output_q  <= output_d;
        result_q  <= output_q;
        valid_q   <= {valid_q[LATENCY-2:0], in_valid};
    end
    assign out_valid = valid_q[LATENCY-1];
    assign result = result_q.value;
endmodule
