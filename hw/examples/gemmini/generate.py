#!/usr/bin/env python3
import argparse, json, os, re, shutil, subprocess, sys
from pathlib import Path

HERE   = Path(__file__).resolve().parent
CHISEL = HERE / "chisel"
MESHES = HERE / "meshes"
BUILD  = HERE / "build"

# chisel/build.sbt's source variables -> (repository, commit)
PINS = {"GEMMINI_SRC": ("https://github.com/ucb-bar/gemmini", "8c3f9923"),
        "HARDFLOAT_SRC": ("https://github.com/ucb-bar/berkeley-hardfloat", "4225367e")}

MESH = ("dim", "tile", "tile_latency", "output_delay", "input_width", "output_width", "acc_width")  # MeshConfig's
SOCKET = ("matmul_queue_depth", "row_queue_depth")
DATAFLOWS = ("ws", "os", "both")                    # MXU_DATAFLOW 1, 2, 3

# meshes/<mesh>_cfg.sv, from the generator's params.json
CFG = """\
// Generated by examples/gemmini/generate.py: the Gemmini Mesh configuration of
// examples/gemmini/meshes/{name}.v (MATMULS: its max_simultaneous_matmuls).
package gemmini_mesh_cfg;
    localparam int unsigned DIM          = {dim};
    localparam int unsigned TILE         = {tile};
    localparam int unsigned TILE_LATENCY = {tile_latency};
    localparam int unsigned OUTPUT_DELAY = {output_delay};
    localparam int unsigned INPUT_WIDTH  = {input_width};
    localparam int unsigned OUTPUT_WIDTH = {output_width};
    localparam int unsigned ACC_WIDTH    = {acc_width};
    localparam int unsigned MATMULS      = {max_simultaneous_matmuls};
    localparam int unsigned SHIFT_WIDTH  = {shift_width};
endpackage : gemmini_mesh_cfg
"""

# units/<unit>.toml
UNIT = """\
# Written by: python3 examples/gemmini/generate.py {command}
# sources: the mesh, from Gemmini's generator; adapter: BYOM's side
sources = ["examples/gemmini/meshes/{name}_cfg.sv", "examples/gemmini/meshes/{name}.v"]
adapter = ["examples/gemmini/adapter.sv"]

[operands]
code_bits = {input_width}
w_bits = {input_width}
a_bits = {input_width}
prod_w = {product_width}
psum_w = {output_width}
w_twos = true

[socket]
dataflow = {dataflow_bits}              # 1 weight-stationary, 2 output-stationary, 3 both
{socket}
"""

def strip_locators(verilog): return re.sub(r"[ \t]*// @\[[^\]]*\]$", "", verilog, flags=re.M)

def prefix_modules(verilog):
    names = re.findall(r"^module (\w+)\(", verilog, re.M)
    alt = "|".join(sorted(names, key=len, reverse=True))
    verilog = re.sub(rf"^module ({alt})\(", r"module gemmini_\1(", verilog, flags=re.M)
    return re.sub(rf"^(\s+)({alt})(\s+\w+\s*\()", r"\1gemmini_\2\3", verilog, flags=re.M)

def sources():
    env = {}
    for var, (url, commit) in PINS.items():
        d = BUILD / f"{url.rsplit('/', 1)[1]}-{commit}"
        if not (d / ".git").exists():
            subprocess.run(["git", "clone", "--quiet", "--filter=blob:none", "--no-checkout", url, str(d)], check=True)
            subprocess.run(["git", "-C", str(d), "checkout", "--quiet", commit], check=True)
        env[var] = str(d)
    return env


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("unit", help="the unit file to write: units/UNIT.toml")
    ap.add_argument("--dataflow", choices=DATAFLOWS, required=True)
    for k in MESH:
        ap.add_argument("--" + k.replace("_", "-"), type=int, help="a Mesh setting")
    for k in SOCKET:
        ap.add_argument("--" + k.replace("_", "-"), type=int, help="a socket option")
    a = vars(ap.parse_args())
    out = BUILD / "emitted"
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    settings = ",".join(f"{k}={a[k]}" for k in ("dataflow",) + MESH if a[k] is not None)
    subprocess.run(["sbt", f"run {out} {settings}"], cwd=CHISEL, check=True, env={**os.environ, **sources()})
    (d,) = out.iterdir()
    p = json.loads((d / "params.json").read_text())
    socket = {"mode_word": True} if a["dataflow"] == "both" else {}     # both: the run's dataflow is bit 0 of mxu_mode
    socket |= {k: a[k] for k in SOCKET if a[k] is not None}
    unit = UNIT.format(**p, product_width=2 * p["input_width"], dataflow_bits=DATAFLOWS.index(a["dataflow"]) + 1,
       command=" ".join(sys.argv[1:]), socket="\n".join(f"{k} = {str(v).lower()}" for k, v in socket.items()))
    for f, text in ((MESHES / f"{p['name']}.v", prefix_modules(strip_locators((d / "FlatMesh.v").read_text()))),
        (MESHES / f"{p['name']}_cfg.sv", CFG.format(**p)), (HERE / "units" / f"{a['unit']}.toml", unit)):
        f.write_text(text)
        print("wrote", f.relative_to(HERE))
